BUGCHECKS: Dict[int, BugCheck] = {b.code: b for b in _ENTRIES}


def lookup(code: int) -> Optional[BugCheck]:
    """Вернуть описание STOP-кода или None, если он неизвестен."""
    if code in BUGCHECKS:
        return BUGCHECKS[code]
    # Иногда код приходит расширенным (старший байт-модификатор) — пробуем
    # младшие 32 бита.
    low = code & 0xFFFFFFFF
    return BUGCHECKS.get(low)


